const byLocale: Record<AppLocale, Messages> = { ja, en };

export function tx(
  locale: AppLocale,
  key: string,
  vars?: Record<string, string | number>
): string {
  let s = byLocale[locale]?.[key] ?? byLocale.ja[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return s;
}

export function useTranslation() {
  const locale = useLocaleStore((s) => s.locale);
  const setLocale = useLocaleStore((s) => s.setLocale);
  const t = useCallback((key: string, vars?: Record<string, string | number>) => tx(locale, key, vars), [locale]);
  return { t, locale, setLocale, tx: (key: string, vars?: Record<string, string | number>) => tx(locale, key, vars) };
}

/** 日付の toLocaleString 用 */
export function dateLocaleTag(locale: AppLocale): string {
  return locale === 'en' ? 'en-US' : 'ja-JP';
}
